// Simpele {{token}}-substitutie — geen library nodig voor het handjevol strings met een dynamisch
// onderdeel. Onbekende tokens blijven gewoon staan i.p.v. te crashen.
function interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{\{(\w+)\}\}/g, (match, token) => (token in vars ? String(vars[token]) : match));
}

// t(lang, key, vars): vertaalt key naar de gekozen taal, met fallback op Nederlands en dan de key zelf
// (nooit een crash/lege string bij een ontbrekende vertaling — een ontbrekende key toont zichzelf,
// wat meteen opvalt i.p.v. onopgemerkt te blijven).
export function t(lang, key, vars) {
  const table = STRINGS[lang] ?? STRINGS[DEFAULT_LANGUAGE];
  const str = table[key] ?? STRINGS[DEFAULT_LANGUAGE][key] ?? key;
  return interpolate(str, vars);
}
